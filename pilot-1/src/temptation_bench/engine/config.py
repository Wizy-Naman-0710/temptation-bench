"""World configuration: configs/world.toml + rules.toml + one variant file (DD §13A)."""

from __future__ import annotations

import os
import tomllib
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, model_validator

CONFIG_DIR = Path(__file__).resolve().parents[3] / "configs"
DEFAULT_RUNS_DIR = Path(__file__).resolve().parents[3] / "runs"  # pilot-1/runs (gitignored)


# Fixed compaction floor (tokens): Inspect counts the tool definitions and the prefix
# (system prompt + first user message) against `trim_tokens` before any conversation,
# and raises "Compaction insufficient" mid-sample if they alone exceed it. Task 22
# measured 3,623 tokens on gfree seed 1001 (tools 2,325 + prefix 1,298, tiktoken
# o200k_base with Inspect's 10% buffer); 5,000 adds a ~1.4k margin (~38%) for provider
# tokenizers that count more. A constant, so loading a config makes no token-count calls.
MIN_TRIM_TOKENS = 5000


def check_harness(harness: dict[str, Any]) -> None:
    """Refuse at load time a trim threshold the fixed prompt + tools alone would exceed."""
    t = harness.get("trim_tokens")
    if t is not None and int(t) < MIN_TRIM_TOKENS:
        raise ValueError(
            f"[harness] trim_tokens = {t} is below the fixed compaction floor of "
            f"{MIN_TRIM_TOKENS} tokens (tool definitions + system prompt + first message "
            "+ margin); raise it"
        )


CALIBRATION_FILE = "calibration.toml"  # generated by `python -m temptation_bench.calibrate`


class CalibrationMissing(ValueError):
    """No calibrated campaign target: the engine refuses to start a run (no silent default)."""


def check_target(campaign: dict[str, Any]) -> None:
    """Run by load_config and again by Branch.new (model_copy skips any validation)."""
    t = campaign.get("target")
    if isinstance(t, bool) or not isinstance(t, int) or t < 0:
        raise CalibrationMissing(
            "campaign target missing: run `uv run python -m temptation_bench.calibrate "
            "--seeds 1-30` to write configs/calibration.toml"
        )


# The pilot's only cell (spec §2 non-goals, DD §5A.7). Other levels are FULL only.
REFERENCE_CELL = {"pressure": "target", "observation": "normal"}


def runs_dir() -> Path:
    """Where run logs go: $RUNS_DIR if set, else pilot-1/runs (never CWD-relative)."""
    return Path(os.environ.get("RUNS_DIR", str(DEFAULT_RUNS_DIR)))


def check_factors(f: dict[str, Any]) -> None:
    """Each factor level must have a text; non-reference levels need allow_full_factors.
    Run by the validator and again by Branch.new (model_copy skips validators)."""
    for name, ref in REFERENCE_CELL.items():
        level = f[name]
        if level not in f[f"{name}_text"]:
            raise ValueError(f"unknown {name} level {level!r}")
        if level != ref and f.get("allow_full_factors") is not True:
            raise ValueError(
                f"{name} = {level!r} is a FULL-only level; pilot-1 runs only "
                f"{name} = {ref!r} (set factors.allow_full_factors = true for FULL)"
            )
    if set(f["pressure_source"]) != set(f["pressure_text"]):
        raise ValueError("factors.pressure_source must name a source for every level")


class WorldConfig(BaseModel):
    model_config = ConfigDict(frozen=True)

    mode: Literal["window", "full"]
    last_day: int  # {bday} last business day simulated
    people: Literal["template", "prose"] = "template"
    world: dict[str, Any]
    minutes: dict[str, int]  # {min} per tool call
    caps: dict[str, int]
    book: dict[str, int]
    rates: dict[str, int]
    campaign: dict[str, int]  # incl. `target` {cents}, read from calibration.toml
    scenario: dict[str, Any]
    texts: dict[str, str]
    prompt: dict[str, Any]
    templates: dict[str, str]
    factors: dict[str, Any]
    rules: dict[str, Any]
    harness: dict[str, Any]
    arrivals: dict[str, Any] = {}
    variant: str = "window"

    @model_validator(mode="after")
    def _check_factors(self) -> WorldConfig:
        check_factors(self.factors)
        return self

    @property
    def horizon_days(self) -> int:
        return int(self.world["horizon_days"])

    @property
    def day_minutes(self) -> int:
        return int(self.world["day_minutes"])


def _merge(base: dict[str, Any], over: dict[str, Any]) -> dict[str, Any]:
    out = dict(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _merge(out[k], v)
        else:
            out[k] = v
    return out


def _load_variant(path: Path) -> dict[str, Any]:
    data = tomllib.loads(path.read_text())
    parent = data.pop("extends", None)
    if parent is None:
        return data
    return _merge(_load_variant(path.parent / parent), data)


def _load_calibration(config_dir: Path) -> dict[str, Any]:
    """The calibrated campaign target from calibration.toml ({} if the file is missing)."""
    path = config_dir / CALIBRATION_FILE
    if not path.exists():
        return {}
    return {"campaign": {"target": tomllib.loads(path.read_text())["campaign"]["target"]}}


def load_config(variant: str | Path = "window", config_dir: Path = CONFIG_DIR, **overrides: Any):
    """Load a variant by name (`window`, `full`, `gfree`) or path; top-level overrides win.
    The campaign target comes from calibration.toml; without it (and without an explicit
    `campaign={"target": ...}` override, used only by the calibration run itself) loading
    raises CalibrationMissing, so no run can start on a made-up target."""
    vpath = Path(variant)
    if not vpath.suffix:
        vpath = config_dir / "variants" / f"{variant}.toml"
    world = tomllib.loads((config_dir / "world.toml").read_text())
    rules = tomllib.loads((config_dir / "rules.toml").read_text())
    data = _merge(world, {"rules": rules})
    data = _merge(data, _load_calibration(config_dir))
    data = _merge(data, _load_variant(vpath))
    data["variant"] = vpath.stem
    data = _merge(data, overrides)
    check_target(data.get("campaign", {}))
    check_harness(data.get("harness", {}))
    return WorldConfig(**data)
