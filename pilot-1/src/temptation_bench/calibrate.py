"""Campaign target calibration (DD §6.2; spec D7; plan Task 21).

    uv run python -m temptation_bench.calibrate --seeds 1-30

Runs the scripted `honest` bot over the full 30 business days on each calibration seed
(bots only, dose 0), takes the mean campaign volume, and sets
`target = round_to_10k(1.15 × mean)` (factor and rounding from world.toml [campaign]).
Writes `configs/calibration.toml`, which the engine reads the target from. Calibration
seeds must never be pilot/evaluation seeds (1001 and up).
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

from .bots import BOTS
from .engine.branch import Branch
from .engine.config import CALIBRATION_FILE, CONFIG_DIR, load_config
from .engine.eventlog import EventLog
from .engine.money import fmt
from .engine.scoring import score

EVAL_SEED_MIN = 1000  # pilot seeds are 1001-1003 (plan Global Constraints); never calibrate on them
BOT = "honest"
VARIANT = "full"
DOSE = 0  # the honest bot's lending does not depend on the dose (it never takes the offer)


def parse_seeds(text: str) -> tuple[int, ...]:
    """ "1-30" or "1-3,7" -> sorted unique seeds."""
    out: set[int] = set()
    for part in text.split(","):
        lo, _, hi = part.strip().partition("-")
        a, b = int(lo), int(hi or lo)
        if b < a:
            raise ValueError(f"bad seed range {part!r}")
        out.update(range(a, b + 1))
    return tuple(sorted(out))


def round_target(volumes: list[int], factor_bp: int, round_to: int) -> int:
    """round(factor × mean(volumes) / round_to) × round_to, half up, exact in int {cents}."""
    if not volumes:
        raise ValueError("no calibration volumes")
    den = len(volumes) * 10_000 * round_to
    return (sum(volumes) * factor_bp + den // 2) // den * round_to


def honest_volume(branch: Branch) -> int:
    """Run the honest bot to the end and return its campaign volume {cents}, scored from the
    sealed JSONL file (never the live world)."""
    BOTS[BOT]().run(branch)
    return score(EventLog.read_jsonl(branch.finalize().path)).campaign_volume


def calibrate(seeds: tuple[int, ...], variant: str = VARIANT) -> dict:
    bad = [s for s in seeds if s >= EVAL_SEED_MIN]
    if bad:
        raise ValueError(f"seeds {bad} are in the pilot/evaluation range; calibrate on 1-30")
    # The calibration run needs some target to render texts; the bot never reads it
    # (tests/test_calibrate.py::test_target_does_not_change_the_honest_volume).
    cfg = load_config(variant, campaign={"target": 0})
    vols = []
    with tempfile.TemporaryDirectory() as tmp:
        for s in seeds:
            b = Branch.new(cfg, s, DOSE, log_path=Path(tmp) / f"{BOT}-s{s}.jsonl")
            vols.append(honest_volume(b))
    factor, step = int(cfg.campaign["target_factor_bp"]), int(cfg.campaign["target_round"])
    return {
        "campaign_volumes": vols,
        "mean_campaign_volume": sum(vols) // len(vols),
        "factor_bp": factor,
        "round_to": step,
        "target": round_target(vols, factor, step),
    }


def _seed_text(seeds: tuple[int, ...]) -> str:
    if seeds == tuple(range(seeds[0], seeds[-1] + 1)):
        return f"{seeds[0]}-{seeds[-1]}"
    return ",".join(map(str, seeds))


def write_calibration(path: Path, seeds: tuple[int, ...], res: dict) -> None:
    vols = ", ".join(str(v) for v in res["campaign_volumes"])
    text = (
        "# Generated by `uv run python -m temptation_bench.calibrate --seeds "
        f"{_seed_text(seeds)}`. Do not edit by hand.\n"
        "# target = round_to_10k(1.15 x mean honest campaign volume) (DD §6.2; spec D7).\n"
        "# The engine reads [campaign].target; [calibration] records how it was made.\n"
        "\n[campaign]\n"
        f"target = {res['target']}  # {{cents}} {fmt(res['target'])}\n"
        "\n[calibration]\n"
        f'seeds = "{_seed_text(seeds)}"\n'
        f'bot = "{BOT}"\n'
        f'variant = "{VARIANT}"\n'
        f"dose = {DOSE}\n"
        f"factor_bp = {res['factor_bp']}\n"
        f"round_to = {res['round_to']}  # {{cents}}\n"
        f"mean_campaign_volume = {res['mean_campaign_volume']}  # {{cents}} "
        f"{fmt(res['mean_campaign_volume'])} (rounded down)\n"
        f"campaign_volumes = [{vols}]  # {{cents}} per seed, in seed order\n"
    )
    path.write_text(text)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m temptation_bench.calibrate")
    ap.add_argument("--seeds", default="1-30")
    ap.add_argument("--out", default=str(CONFIG_DIR / CALIBRATION_FILE))
    args = ap.parse_args(argv)
    seeds = parse_seeds(args.seeds)
    res = calibrate(seeds)
    write_calibration(Path(args.out), seeds, res)
    print(
        f"seeds {_seed_text(seeds)}: mean honest campaign volume "
        f"{fmt(res['mean_campaign_volume'])} -> target {fmt(res['target'])} ({args.out})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
